"""Arabic text folding and country names written in Arabic.

The statistics of the United Arab Emirates (opendata.fcsc.gov.ae, snapshot of 2024) give every
label in English and Arabic: trade tables by partner country (Country(Arabic): المملكة العربية
السعودية, جمهورية إيران الإسلامية), emirates, regions and nationalities. Arabic spellings vary
in ways that do not change the word: hamza forms of alef (أ إ آ ا), ة and ه, ى and ي at the end
of a word, the tatweel that stretches words (دبـــي), vowel marks (جمهوريّة), the Persian forms
of yeh and kaf (الغربیه), and spaces (مصرالعربية, جمهورية  إيران). ``fold_arabic`` removes these
differences; ``country_key`` also drops spaces and writes غ as ج, as Gulf and Egyptian spellings
do (بنجلاديش for بنغلاديش, هونج كونج for هونغ كونغ).
"""
import re

_MARKS = re.compile("[ً-ٰٟـ‌-‏]")
_LETTERS = str.maketrans({
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا",  # أ إ آ ٱ -> ا
    "ى": "ي",  # ى -> ي
    "ة": "ه",  # ة -> ه
    "ی": "ي", "ک": "ك", "ھ": "ه",  # Persian yeh, keheh, heh
})
_ARABIC = re.compile("[؀-ۿ]")


def fold_arabic(value):
    """Arabic text with one spelling for alef, ta marbuta, final yeh; no vowel marks, tatweel
    or footnote stars; single spaces. Latin text is lower-cased."""
    text = _MARKS.sub("", str(value)).translate(_LETTERS).lower()
    return " ".join(text.replace("*", " ").split()).strip(" -.,")


def has_arabic(value):
    """True when the value has an Arabic letter."""
    return _ARABIC.search(str(value)) is not None


def country_key(value):
    """The folded name without spaces and with غ as ج: the key of the country name list."""
    return fold_arabic(value).replace(" ", "").replace("غ", "ج")


