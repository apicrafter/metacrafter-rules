ICES_QFLAG = frozenset(("<", ">", "D", "Q"))
ICES_BASIS = frozenset(("W", "D", "L"))


def _text(value):
    return "" if value is None else str(value).strip()


def validate_ices_parameter_code(value):
    """A code of the ICES PARAM vocabulary: CD, HG, CB118, BAA."""
    return _text(value) in ICES_PARAM


def validate_ices_matrix_code(value):
    """A code of the ICES MATRX vocabulary: LI, MU, SED63, SB, BI (not Liver)."""
    return _text(value) in ICES_MATRX


def validate_ices_method_of_analysis_code(value):
    """A code of the ICES METOA vocabulary: GC-MS, ICP-MS, GC-ECD, AAS."""
    return _text(value) in ICES_METOA


def validate_ices_station_type(value):
    """A code of the ICES MSTAT vocabulary: B, RH, IH, IH-A."""
    return _text(value) in ICES_MSTAT


def validate_ices_gear_code(value):
    """A code of the ICES Gear vocabulary: GOV, ROT, BT4A, BT8, NCT (not Otter trawl)."""
    return _text(value) in ICES_GEAR


def validate_ices_qualifier_flag(value):
    """A qualifier flag of the ICES environmental format: <, >, D, Q."""
    return _text(value) in ICES_QFLAG


def validate_ices_basis_code(value):
    """A basis of determination of the ICES environmental format: W, D, L."""
    return _text(value) in ICES_BASIS


# Two digits number the row from 01, a letter and a digit name the column: A0 to A3, B0 to L9
# without the letter I, M0 to M8.
_ICES_RECTANGLE = re.compile(r"^(?:0[1-9]|[1-9]\d)(?:A[0-3]|[B-HJ-L]\d|M[0-8])$")


def validate_ices_statistical_rectangle(value):
    """An ICES statistical rectangle: 37F3, 46F2, 34E5 (not 37I2: the letter I is not used)."""
    return bool(_ICES_RECTANGLE.match(_text(value).upper()))


_APHIA_ID = re.compile(r"^[1-9]\d{2,7}(?:\.0)?$")


def validate_worms_aphia_id(value):
    """An AphiaID of the World Register of Marine Species: a whole number of three to eight digits
    (126436 Gadus morhua, 156533). A number read as a float (126436.0) is allowed."""
    return bool(_APHIA_ID.match(_text(value)))


_ASFIS = re.compile(r"^[A-Z]{3}$")


def validate_fao_asfis_code(value):
    """A 3-alpha species code of the FAO ASFIS list: COD, HAD, WHB, MAC."""
    return bool(_ASFIS.match(_text(value)))


# The eleven regions of the Scottish Marine Regions Order 2015 and the sums that the statistics of
# Marine Scotland report.
_SCOTTISH_MARINE_REGIONS = frozenset(("argyll", "clyde", "forth and tay", "moray firth", "north coast", "north east",
                                      "orkney islands", "outer hebrides", "shetland isles", "solway", "west highlands"))
_SMR_SPLIT = re.compile(r"\s*(?:&|,|/)\s*")


def validate_scottish_marine_region(value):
    """A Scottish Marine Region or a sum of them: Outer Hebrides, Shetland Isles, Forth and Tay,
    Argyll & Clyde, West Highlands & North Coast, All Scotland."""
    text = re.sub(r"\s+", " ", _text(value).lower())
    if text in _SCOTTISH_MARINE_REGIONS or text in ("all scotland", "scotland"):
        return True
    parts = [p for p in _SMR_SPLIT.split(text) if p]
    return len(parts) > 1 and all(p in _SCOTTISH_MARINE_REGIONS for p in parts)
